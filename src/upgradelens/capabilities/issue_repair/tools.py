"""Issue-repair tool surface (plan stage S6).

Thin, offline wrappers around the deterministic analyzers. Register them into a
:class:`~upgradelens.tools.registry.ToolRegistry` together with a
:class:`~upgradelens.core.capability.CapabilityRegistry` to exercise the S1
capability tool-gate. The live pipeline (``repair_issue``) calls the analyzers
directly and is independent of this surface.
"""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field

from upgradelens.tools.registry import Tool

from .analyzers import load_issue, locate_root_cause
from .models import IssueRepairReport

__all__ = ["issue_repair_tools", "ISSUE_REPAIR_TOOL_NAMES"]


class LoadIssueInput(BaseModel):
    issue_text: str = Field(description="Raw issue report text.")


class ReproduceIssueInput(BaseModel):
    issue_text: str = Field(description="Raw issue report text.")
    repo_root: str = Field(description="Path to the repository root.")


class LocateRootCauseInput(BaseModel):
    issue_text: str = Field(description="Raw issue report text.")
    repo_root: str = Field(description="Path to the repository root.")


class GeneratePatchInput(BaseModel):
    issue_text: str = Field(description="Raw issue report text.")
    root_cause: str = Field(default="", description="Deterministic root-cause hint.")


class RunTestsInput(BaseModel):
    test_paths: list[str] = Field(description="Test files to run.")


class VerifyFixInput(BaseModel):
    report: IssueRepairReport = Field(description="The repair report to verify.")
    repo_root: str = Field(description="Path to the repository root.")


def _load_issue(args: LoadIssueInput, ctx: Any) -> dict[str, Any]:
    issue = load_issue(args.issue_text)
    return {"issue_id": issue.issue_id, "title": issue.title}


def _reproduce_issue(args: ReproduceIssueInput, ctx: Any) -> dict[str, Any]:
    return {"reproducible": True, "note": "offline stub"}


def _locate_root_cause(args: LocateRootCauseInput, ctx: Any) -> dict[str, Any]:
    issue = load_issue(args.issue_text)
    return {"root_cause": locate_root_cause(issue, args.repo_root)}


def _generate_patch(args: GeneratePatchInput, ctx: Any) -> dict[str, Any]:
    # Offline template; the live pipeline performs this via the model node.
    return {
        "diff": "",
        "target_files": [],
        "note": "real patch generated by the issue_repair model node",
    }


def _run_tests(args: RunTestsInput, ctx: Any) -> dict[str, Any]:
    return {"tests": args.test_paths, "passed": None}


def _verify_fix(args: VerifyFixInput, ctx: Any) -> dict[str, Any]:
    from .verifiers import verify_issue_repair

    result = verify_issue_repair(args.report, args.repo_root)
    return {
        "passed": result.passed,
        "summary": result.summary,
        "checks": [c.model_dump() for c in result.checks],
    }


ISSUE_REPAIR_TOOL_NAMES: tuple[str, ...] = (
    "load_issue",
    "reproduce_issue",
    "locate_root_cause",
    "generate_patch",
    "run_tests",
    "verify_fix",
)


def issue_repair_tools() -> list[Tool]:
    """The six deterministic issue-repair tools."""
    return [
        Tool(
            name="load_issue",
            description="Parse a raw issue report into a structured Issue.",
            input_model=LoadIssueInput,
            handler=_load_issue,
        ),
        Tool(
            name="reproduce_issue",
            description="Attempt to reproduce the issue (offline stub).",
            input_model=ReproduceIssueInput,
            handler=_reproduce_issue,
        ),
        Tool(
            name="locate_root_cause",
            description="Keyword scan of repo symbols for likely culprits.",
            input_model=LocateRootCauseInput,
            handler=_locate_root_cause,
        ),
        Tool(
            name="generate_patch",
            description="Generate a patch for the issue (offline template).",
            input_model=GeneratePatchInput,
            handler=_generate_patch,
        ),
        Tool(
            name="run_tests",
            description="Run the suggested regression tests.",
            input_model=RunTestsInput,
            handler=_run_tests,
        ),
        Tool(
            name="verify_fix",
            description="Verify the repair patch targets real files.",
            input_model=VerifyFixInput,
            handler=_verify_fix,
        ),
    ]
